#!/usr/bin/env python3
"""
check_anchors.py — проверяет, что внутренние ссылки README ведут в существующие
заголовки.

Зачем отдельный скрипт. Содержание большое, а битая ссылка ломается молча: гитхаб
ничего не прокручивает и ошибки не показывает. Проглядеть её глазами легко.

Правило проверено на живом гитхабе, а не взято из головы: в якоре остаются только
буквы, цифры, подчёркивание и дефис, каждый пробел превращается в дефис. Всё
остальное выбрасывается — включая кавычки «» и знак умножения ×.

Две ловушки, обе стоили времени.

Пробелы НЕ склеиваются. У заголовка «`captions.py` — караоке-субтитры» тире
выбрасывается, а два пробела вокруг него дают ДВА дефиса подряд:
`captionspy--караоке-субтитры`. Схлопывание пробелов в один дефис объявляет
битыми сразу все такие заголовки.

Типографика уходит, кириллица остаётся. Заголовок с «Стример» в кавычках даёт
якорь без кавычек. Проверено нажатием ссылки на самом гитхабе: с кавычками в
якоре перехода нет, без них есть. Поэтому знак × в заголовке лучше не держать
вовсе — якорь «1080×1920» превращается в «10801920», что читателю ни о чём не
говорит. Латинская x сохраняется.

    python3 scripts/check_anchors.py            # код возврата 1, если есть битые
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

# всё, что не буква/цифра/подчёркивание, не пробел и не дефис — выбрасывается.
# \w с re.UNICODE держит кириллицу, поэтому русские заголовки работают.
DROP = re.compile(r"[^\w\s-]", re.UNICODE)

# Символ опасен не тем, что исчезает, а тем, что при исчезновении СКЛЕИВАЕТ
# соседей: «1080×1920» превращается в «10801920». Тире же окружено пробелами,
# оно оставляет за собой два дефиса и ничего не портит.
# Точка из имён модулей исключена: «story.py» -> «storypy» читается нормально
# и встречается в каждом втором заголовке — предупреждать о ней значит шуметь.
GLUES = re.compile(r"\w([^\w\s.-])\w", re.UNICODE)


def slug(heading: str) -> str:
    """Заголовок -> якорь по правилам гитхаба."""
    s = heading.strip().lower()
    s = s.replace("`", "").replace("*", "")   # разметка в якорь не попадает
    # пробел -> дефис поштучно: схлопывать нельзя, см. пояснение выше
    return DROP.sub("", s).replace(" ", "-")


def check(path: Path) -> int:
    text = path.read_text(encoding="utf-8")

    # заголовки берём только вне блоков кода: внутри ``` строки с # не заголовки
    in_code, heads = False, {}
    for ln in text.splitlines():
        if ln.lstrip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        m = re.match(r"^(#{1,6})\s+(.+?)\s*$", ln)
        if m:
            heads[slug(m.group(2))] = m.group(2)

    links = re.findall(r"\]\(#([^)]+)\)", text)
    bad = [l for l in links if l not in heads]

    print(f"{path.name}: заголовков {len(heads)}, "
          f"внутренних ссылок {len(links)}, битых {len(bad)}")
    for b in dict.fromkeys(bad):
        print(f"  битая ссылка: #{b}")
        near = [h for h in heads if h[:14] == b[:14]]
        for n in near:
            print(f"      похоже, нужен: #{n}")

    # предупреждение, а не ошибка: ссылка рабочая, но якорь выйдет невнятным
    for anchor, head in heads.items():
        hit = sorted({m.group(1) for m in GLUES.finditer(head)})
        if hit:
            print(f"  внимание: в заголовке «{head}» символ "
                  f"{' '.join(hit)} склеивает слова в якоре -> #{anchor}")
    return 1 if bad else 0


if __name__ == "__main__":
    root = Path(__file__).parent.parent
    files = [Path(a) for a in sys.argv[1:]] or [root / "README.md"]
    sys.exit(max(check(f) for f in files))
